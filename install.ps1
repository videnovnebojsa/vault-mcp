Write-Host ""
Write-Host "Connect Claude Code" -ForegroundColor White
Write-Host ("─" * 19)
Write-Host "Add to " -NoNewline; Write-Host ".mcp.json" -ForegroundColor Cyan -NoNewline; Write-Host " in your project root:"
Write-Host @"
{
  "mcpServers": {
    "vault": { "type": "http", "url": "http://127.0.0.1:$MCP_PORT/mcp" }
  }
}
"@

Write-Host ""
Write-Host "Connect Claude Desktop" -ForegroundColor White
Write-Host ("─" * 22)
Write-Host "How it fits together:"
Write-Host "  • The background service above runs the HTTP server (vault-mcp.exe, no args)."
Write-Host "  • Claude Desktop speaks stdio, not HTTP, so it spawns vault-mcp.exe bridge"
Write-Host "    on demand — a stdio↔HTTP proxy to that running server, not a second server."
Write-Host ""

# Claude Desktop's config path differs between the classic and Microsoft Store builds.
# Point the user at the file that actually exists rather than a single hardcoded path.
$cdCfg = Get-ClaudeDesktopConfigPaths
if ($cdCfg.Found.Count -eq 1) {
    Write-Host "Add to " -NoNewline; Write-Host $cdCfg.Found[0] -ForegroundColor Cyan -NoNewline; Write-Host ":"
} elseif ($cdCfg.Found.Count -gt 1) {
    Write-Host "Add to your Claude Desktop config — edit whichever your build uses:"
    foreach ($p in $cdCfg.Found) { Write-Host "  " -NoNewline; Write-Host $p -ForegroundColor Cyan }
} else {
    Write-Host "Add to your " -NoNewline; Write-Host "claude_desktop_config.json" -ForegroundColor Cyan -NoNewline; Write-Host ":"
    Write-Host "  Classic build:  " -NoNewline; Write-Host $cdCfg.Standard -ForegroundColor Cyan
    Write-Host "  MS Store build: " -NoNewline; Write-Host $cdCfg.MsStore -ForegroundColor Cyan
}
# Escape backslashes so the Windows binary path is valid JSON.
$binJson = $BIN_PATH -replace '\\', '\\'
Write-Host @"
{
  "mcpServers": {
    "vault": {
      "command": "$binJson",
      "args": ["bridge"],
      "env": { "VAULT_MCP_URL": "http://127.0.0.1:$MCP_PORT/mcp" }
    }
  }
}
"@

Write-Host ""
Write-Host "Verify" -ForegroundColor White
Write-Host ("─" * 6)
Write-Host "  " -NoNewline; Write-Host "curl http://localhost:$MCP_PORT/health" -ForegroundColor Cyan

Write-Host ""
Write-Host "Reconfigure anytime" -ForegroundColor White
Write-Host ("─" * 19)
Write-Host "  " -NoNewline; Write-Host ".\install.ps1 -Configure" -ForegroundColor Cyan -NoNewline
Write-Host "   — quick wizard (no download)"
Write-Host "  " -NoNewline; Write-Host "bun run configure" -ForegroundColor Cyan -NoNewline
Write-Host "          — full editor (requires Bun)"
Write-Host "  " -NoNewline; Write-Host $CFG_FILE -ForegroundColor Cyan -NoNewline
Write-Host "  — edit directly"

Write-Host ""
Write-Host "✔ Done! vault-mcp is ready." -ForegroundColor Green
Write-Host ""
